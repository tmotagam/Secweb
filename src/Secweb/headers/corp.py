from __future__ import annotations
from typing import TYPE_CHECKING

from ..middleware import SetMiddleware

if TYPE_CHECKING:
    from .._types import Cross_Origin_Resource_Policy_Options
    from starlette.applications import Starlette

def Cross_Origin_Resource_Policy(app: Starlette | None = None, option: Cross_Origin_Resource_Policy_Options = 'same-origin') -> tuple[bytes, bytes]:
    """
    Sets the `Cross-Origin-Resource-Policy` (CORP) HTTP response header.

    The CORP header conveys a desire that the browser blocks no-cors cross-origin/cross-site requests to the given resource.
    It provides protection against certain requests like those generated by `<img>` and `<script>` elements.

    Args:
        app (Starlette | None, optional): An optional Starlette application instance. 
            If provided, the CORP header is injected into the application via middleware. Defaults to None.
        option (Cross_Origin_Resource_Policy_Options, optional): The policy directive to apply.
            Valid values are: "same-origin", "same-site", or "cross-origin".
            Defaults to 'same-origin'.

    Returns:
        tuple[bytes, bytes]: A tuple representing the header key and its computed value, 
            e.g., `(b"Cross-Origin-Resource-Policy", b"same-origin")`.

    Raises:
        ValueError: If an unsupported policy directive is provided.

    Example:
        >>> Cross_Origin_Resource_Policy(app, option="same-site")
        (b'Cross-Origin-Resource-Policy', b'same-site')
    """
    if option not in ('same-origin', 'same-site', 'cross-origin'):
        raise ValueError('Invalid option for Cross-Origin-Resource-Policy (must be "same-origin", "same-site", or "cross-origin")')
    if app is not None:
        app.add_middleware(SetMiddleware, headers=[(b'Cross-Origin-Resource-Policy', option.encode('latin-1'))])
    return (b'Cross-Origin-Resource-Policy', option.encode('latin-1'))
